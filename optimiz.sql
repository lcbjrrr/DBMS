ALTER TABLE school_data
    ADD COLUMN YY INT,
    ADD COLUMN DD INT;

UPDATE school_data
SET YY = NULLIF(split_part(AC_YEAR, '-', 1), '')::INT,
    DD = NULLIF(split_part(AC_YEAR, '-', 2), '')::INT
WHERE AC_YEAR ~ '^\d+-\d+$';

ALTER TABLE school_data ADD COLUMN DMY DATE;

UPDATE school_data
SET DMY = make_date(YY + 1, 12, 1)
WHERE YY IS NOT NULL AND DD IS NOT NULL;

SELECT DISTNAME,
       COUNT(*) AS school_count
FROM school_data
WHERE DMY >= '2006-01-01'
  AND DMY <  '2007-01-01'
GROUP BY DISTNAME
ORDER BY school_count DESC;

